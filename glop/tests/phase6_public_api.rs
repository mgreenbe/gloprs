use glop::lp_solver::LPSolver;
use glop::parameters::InitialBasisHeuristic;
use lp_data::lp_data::LinearProgram;

fn model() -> LinearProgram {
    let mut lp = LinearProgram::new();
    let x = lp.create_new_variable();
    let y = lp.create_new_variable();
    let row = lp.create_new_constraint();
    lp.set_variable_bounds(x, 0.0, 10.0);
    lp.set_variable_bounds(y, 0.0, 10.0);
    lp.set_constraint_bounds(row, 5.0, f64::INFINITY);
    lp.set_coefficient(row, x, 1.0);
    lp.set_coefficient(row, y, 1.0);
    lp.set_objective_coefficient(x, 1.0);
    lp.set_objective_coefficient(y, 2.0);
    lp.clean_up();
    lp
}

fn configured_solver() -> LPSolver {
    let mut solver = LPSolver::new();
    let parameters = solver.parameters_mut();
    parameters.use_preprocessing = false;
    parameters.use_scaling = false;
    parameters.initial_basis = InitialBasisHeuristic::None;
    parameters.exploit_singleton_column_in_initial_basis = false;
    solver
}

#[test]
fn public_basis_round_trip_matches_native_glop() {
    // Reference generated by tools/phase6_warm_start_reference_adapter.cc.
    let lp = model();
    let mut cold = configured_solver();
    let result = cold.solve_result(&lp);
    assert_eq!(result.status.to_string(), "OPTIMAL");
    assert_eq!(result.simplex_iterations, 2);
    assert_eq!(result.objective_value.to_bits(), 4_617_315_517_961_601_024);
    assert_eq!(result.variable_values.as_slice(), &[5.0, 0.0]);
    assert_eq!(
        result.variable_statuses[lp_data::lp_types::ColIndex::new(0)].to_string(),
        "BASIC"
    );
    let basis = cold.export_basis();
    let mut warm = configured_solver();
    warm.import_basis(&basis);
    let result = warm.solve_result(&lp);
    assert_eq!(result.status.to_string(), "OPTIMAL");
    assert_eq!(result.simplex_iterations, 0);
    assert_eq!(result.objective_value.to_bits(), 4_617_315_517_961_601_024);
    assert_eq!(result.variable_values.as_slice(), &[5.0, 0.0]);
    assert_eq!(warm.export_basis(), basis);
}

#[test]
fn unsupported_options_fail_explicitly() {
    let lp = model();
    let mut solver = configured_solver();
    solver.parameters_mut().use_absl_random = true;
    let result = solver.solve_result(&lp);
    assert_eq!(result.status.to_string(), "ABNORMAL");
    assert_eq!(result.simplex_iterations, 0);
    assert_eq!(
        solver.last_error(),
        Some("parameter 'use_absl_random' is not supported by gloprs")
    );
}

#[test]
fn clear_retains_parameters_but_discards_warm_start() {
    let lp = model();
    let mut solver = configured_solver();
    assert_eq!(solver.solve_result(&lp).simplex_iterations, 2);
    solver.clear();
    assert!(!solver.parameters().use_preprocessing);
    assert!(!solver.parameters().use_scaling);
    assert_eq!(solver.solve_result(&lp).simplex_iterations, 2);
}
